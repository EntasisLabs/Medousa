fn pretty(value: &Value) -> String {
    let mut text = serde_json::to_string_pretty(value).expect("json");
    if !text.ends_with('\n') {
        text.push('\n');
    }
    text
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::registry::ContractRegistry;
    use crate::spec::{
        Audience, FeatureProfile, HttpMethod, OperationSpec, ResponseSpec, SchemaRef, Stability,
        StreamSpec,
    };

    fn liveness() -> OperationSpec {
        OperationSpec {
            operation_id: "liveness.get".into(),
            stability: Stability::Stable,
            feature_profile: FeatureProfile::Core,
            audience: Audience::PublicSdk,
            method: HttpMethod::Get,
            path: "/health".into(),
            parameters: Vec::new(),
            request_body: None,
            responses: vec![ResponseSpec {
                status: 200,
                media_type: "application/json".into(),
                schema: SchemaRef::named("HealthLiveness"),
            }],
            error_codes: vec!["internal_failure".into()],
            trust_group: "liveness".into(),
            credential_scheme: "none".into(),
            capabilities: Vec::new(),
            browser_policy: "public".into(),
            body_limit: 1024,
            rate_limit_class: "liveness".into(),
            bootstrap_public: true,
            stream: None,
            deprecation: None,
        }
    }

    fn stream_op() -> OperationSpec {
        let mut spec = liveness();
        spec.operation_id = "interactive.stream.get".into();
        spec.path = "/v1/interactive/turn/{id}/stream".into();
        spec.bootstrap_public = false;
        spec.trust_group = "portal".into();
        spec.capabilities = vec!["workshop.read".into()];
        spec.rate_limit_class = "stream".into();
        spec.stream = Some(StreamSpec::json_events(SchemaRef::named(
            "TurnStreamEnvelopeV2",
        )));
        spec.responses = vec![ResponseSpec {
            status: 200,
            media_type: "text/event-stream".into(),
            schema: SchemaRef::named("TurnStreamEnvelopeV2"),
        }];
        spec.with_path_parameters()
    }

    #[test]
    fn generation_is_byte_deterministic() {
        let mut registry = ContractRegistry::new();
        registry.register(liveness()).unwrap();
        registry.register(stream_op()).unwrap();
        let first = generate_artifacts(&registry);
        let second = generate_artifacts(&registry);
        assert_eq!(first.openapi_json, second.openapi_json);
        assert_eq!(first.route_inventory_json, second.route_inventory_json);
        assert!(first.openapi_json.contains("\"openapi\": \"3.2.0\""));
        assert!(first.openapi_json.contains("x-medousa-stream"));
        assert!(first.openapi_json.contains("itemSchema"));
        assert!(!first.rust_ops.contains("SSE"));
    }

    #[test]
    fn generate_twice_into_temp_dirs_is_byte_identical() {
        let mut registry = ContractRegistry::new();
        registry.register(liveness()).unwrap();
        let first = generate_artifacts(&registry);
        let second = generate_artifacts(&registry);
        let left = std::env::temp_dir().join("medousa-contract-a");
        let right = std::env::temp_dir().join("medousa-contract-b");
        std::fs::create_dir_all(&left).unwrap();
        std::fs::create_dir_all(&right).unwrap();
        std::fs::write(left.join("openapi.json"), &first.openapi_json).unwrap();
        std::fs::write(right.join("openapi.json"), &second.openapi_json).unwrap();
        assert_eq!(
            std::fs::read(left.join("openapi.json")).unwrap(),
            std::fs::read(right.join("openapi.json")).unwrap()
        );
    }

    fn websocket_op() -> OperationSpec {
        let mut spec = liveness();
        spec.operation_id = "code.lsp.get".into();
        spec.path = "/v1/code/lsp".into();
        spec.bootstrap_public = false;
        spec.trust_group = "portal".into();
        spec.capabilities = vec!["workshop.read".into()];
        spec.stream = Some(StreamSpec::websocket(SchemaRef::named("JsonRpcMessage")));
        spec.responses = vec![ResponseSpec {
            status: 200,
            media_type: "application/json".into(),
            schema: SchemaRef::named("JsonRpcMessage"),
        }];
        spec
    }

    #[test]
    fn websocket_openapi_keeps_json_and_is_not_sse() {
        let mut registry = ContractRegistry::new();
        registry.register(websocket_op()).unwrap();
        let artifacts = generate_artifacts(&registry);
        assert!(artifacts.openapi_json.contains("\"transport\": \"websocket\""));
        assert!(!artifacts.openapi_json.contains("text/event-stream"));
        assert!(artifacts.route_inventory_json.contains("\"streaming\": false"));
        assert!(artifacts.route_inventory_json.contains("\"stream_transport\": \"websocket\""));
        assert!(artifacts.rust_ops.contains("streaming: false"));
    }

    #[test]
    fn catalog_named_schema_is_ingested() {
        let mut spec = liveness();
        spec.responses[0].schema = SchemaRef::named("HealthResponse");
        let mut registry = ContractRegistry::new();
        registry.register(spec).unwrap();
        let mut catalog = BTreeMap::new();
        catalog.insert(
            "HealthResponse".into(),
            json!({
                "type": "object",
                "properties": { "ok": { "type": "boolean" } }
            }),
        );
        let openapi = generate_openapi(&registry, &catalog);
        assert!(openapi.contains("\"HealthResponse\""));
        assert!(openapi.contains("\"ok\""));
        assert!(!openapi.contains("x-medousa-unresolved"));
        let missing = generate_openapi(&registry, &BTreeMap::new());
        assert!(missing.contains("x-medousa-unresolved"));
    }
}
